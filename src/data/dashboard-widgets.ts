export const widgetById = new Map(widgetCatalogue.map((w) => [w.id, w]));

export const widgetCategories: ("All" | WidgetCategory)[] = ["All", "Overview", "Calling", "Performance", "Leads", "Campaigns", "AI", "Quality", "Intelligence", "Tasks", "Alerts"];

export function resolveData(def: WidgetDefinition, scope: DataScope): WidgetData {
  const d = def.data;
  if ("kind" in d) return d;
  return d[scope] ?? d.workspace ?? d.team ?? d.own ?? { kind: "status", items: [] };
}

export function resolveTitle(def: WidgetDefinition, scope: DataScope) {
  return def.scopedTitle?.[scope] ?? def.title;
}

/* -------------------------------------------------------- Default layouts */

const inst = (widgetId: string, w?: WidgetWidth, h?: WidgetHeight): WidgetInstance => {
  const def = widgetById.get(widgetId);
  if (!def) throw new Error(`Unknown widget ${widgetId}`);
  return { instanceId: `${widgetId}-default`, widgetId, size: { w: w ?? def.defaultSize.w, h: h ?? def.defaultSize.h } };
};

