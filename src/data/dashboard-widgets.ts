/* ------------------------------------------------------------------ Types */

export type AppRoute = LinkProps["to"];
export type SystemRole = "admin" | "supervisor" | "agent";
export type DataScope = "workspace" | "team" | "own";

export type WidgetCategory =
  | "Overview"
  | "Calling"
  | "Performance"
  | "Leads"
  | "Campaigns"
  | "AI"
  | "Quality"
  | "Intelligence"
  | "Tasks"
  | "Alerts";

export type WidgetType = "KPI" | "Chart" | "Table" | "List" | "Action" | "Alert" | "Status" | "Insight";

export type WidgetWidth = 3 | 4 | 6 | 8 | 12;
export type WidgetHeight = 2 | 3 | 4 | 5 | 6;
export type WidgetSize = { w: WidgetWidth; h: WidgetHeight };

export const widthOptions: WidgetWidth[] = [3, 4, 6, 8, 12];
export const heightOptions: WidgetHeight[] = [2, 3, 4, 5, 6];

export const sizeLabel: Record<WidgetWidth, string> = {
  3: "Small",
  4: "Medium",
  6: "Large",
  8: "Extra large",
  12: "Full width",
};

export type SeriesKey = { key: string; label: string; color: string };

export type WidgetData =
  | {
      kind: "kpi";
      value: string;
      delta?: number;
      hint?: string;
      trend?: number[];
      progress?: number;
      breakdown?: { label: string; value: string }[];
    }
  | { kind: "series"; data: Record<string, string | number>[]; keys: SeriesKey[]; xKey: string; defaultChart?: "area" | "bar" | "line" }
  | { kind: "donut"; items: { label: string; value: number; color: string }[]; center?: string }
  | { kind: "ranked"; items: { label: string; value: number; tone?: string }[]; format?: "number" | "percent" | "score" }
  | { kind: "funnel"; stages: { stage: string; value: number }[] }
  | { kind: "table"; columns: { key: string; label: string; align?: "right" }[]; rows: Record<string, string | number>[] }
  | { kind: "list"; items: { title: string; meta: string; badge?: string; tone?: "good" | "warn" | "bad" | "info"; action?: string }[] }
  | { kind: "actions"; items: { label: string; to: AppRoute; icon: string }[] }
  | { kind: "status"; items: { label: string; value: string; tone?: "good" | "warn" | "bad" | "info" | "muted" }[]; pulse?: boolean }
  | { kind: "progress"; items: { label: string; value: number; target: number; unit?: string }[] }
  | { kind: "insights"; items: { tone: "good" | "warn"; title: string; body: string }[] }
  | { kind: "compare"; aLabel: string; bLabel: string; rows: { metric: string; a: string; b: string }[] }
  | { kind: "heatmap"; days: string[]; hours: string[]; values: number[][] }
  | { kind: "next-call"; name: string; company: string; phone: string; campaign: string; reason: string; queue: number };

export type WidgetDefinition = {
  id: string;
  title: string;
  /** Title override per data scope (e.g. "My calls" for agents, "Team calls" for supervisors). */
  scopedTitle?: Partial<Record<DataScope, string>>;
  description: string;
  category: WidgetCategory;
  type: WidgetType;
  /** Permissions in the workspace "Module:Feature" format. All must be granted. */
  requiredPermissions: string[];
  supportedRoles: SystemRole[];
  defaultSize: WidgetSize;
  minSize: WidgetSize;
  configurable: boolean;
  refreshInterval?: number;
  link?: { to: AppRoute; label: string; search?: Record<string, string> };
  /** Actions shown in the widget "more" menu. */
  actions: string[];
  data: WidgetData | Partial<Record<DataScope, WidgetData>>;
};

export type WidgetInstance = {
  instanceId: string;
  widgetId: string;
  size: WidgetSize;
  config?: { title?: string; chart?: "area" | "bar" | "line"; range?: string };
};

export type DashboardLayout = {
  role: SystemRole;
  widgets: WidgetInstance[];
  updatedAt: string;
};

